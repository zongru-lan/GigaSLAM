def import_tep(tep_root):
    tep_root = str(Path(tep_root).resolve())
    if tep_root not in sys.path:
        sys.path.insert(0, tep_root)
    from src.nn.loss import TrainEgoPathRegressionLoss
    from src.nn.model import RegressionNet
    from src.utils.dataset import PathsDataset
    from src.utils.postprocessing import regression_to_rails

    return PathsDataset, RegressionNet, TrainEgoPathRegressionLoss, regression_to_rails


def set_seed(seed):
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    torch.cuda.manual_seed_all(seed)


def make_rgb_paths_dataset_class(base_cls):
    class RGBPathsDataset(base_cls):
        def __getitem__(self, idx):
            if self.method != "regression":
                raise NotImplementedError("train_ego_path_detector.py only supports regression datasets")
            img_name = self.imgs[idx]
            img = Image.open(os.path.join(self.imgs_path, img_name)).convert("RGB")
            annotation = self.annotations[img_name]
            rails_mask = self.generate_rails_mask(img.size, annotation)
            img, rails_mask = self.random_crop(img, rails_mask)
            img, rails_mask = self.random_flip_lr(img, rails_mask)
            if self.to_tensor:
                img = self.to_tensor(img)
            if self.img_aug:
                img = self.img_aug(img)
            path_gt, ylim_gt = self.generate_target_regression(rails_mask)
            if self.to_tensor:
                path_gt = torch.from_numpy(path_gt)
                ylim_gt = torch.tensor(ylim_gt)
            return img, path_gt, ylim_gt

    return RGBPathsDataset


def load_annotation_count(path):
    with open(path, "r", encoding="utf-8") as f:
        return len(json.load(f))


