class ConsoleLogger:
    def info(self, msg):
        print(msg, flush=True)


def make_dataset(PathsDataset, images_path, annotations_path, config, img_aug, max_items):
    n = load_annotation_count(annotations_path)
    indices = list(range(n))
    if max_items:
        indices = indices[:max_items]
    return PathsDataset(
        imgs_path=images_path,
        annotations_path=annotations_path,
        indices=indices,
        config=config,
        method="regression",
        img_aug=img_aug,
        to_tensor=True,
    )


def target_to_device(target, device):
    return [target[0].to(device), target[1].to(device)]


def train_one_epoch(model, loader, criterion, optimizer, device, amp):
    model.train()
    total_loss = 0.0
    total_items = 0
    scaler = torch.cuda.amp.GradScaler(enabled=amp and device.type == "cuda")
    for data, path_gt, ylim_gt in loader:
        data = data.to(device, non_blocking=True)
        target = [path_gt.to(device, non_blocking=True), ylim_gt.to(device, non_blocking=True)]
        optimizer.zero_grad(set_to_none=True)
        with torch.cuda.amp.autocast(enabled=amp and device.type == "cuda"):
            output = model(data)
            loss = criterion(output, target)
        scaler.scale(loss).backward()
        scaler.step(optimizer)
        scaler.update()
        bs = data.shape[0]
        total_loss += float(loss.detach().cpu()) * bs
        total_items += bs
    return total_loss / max(total_items, 1)


@torch.no_grad()
def evaluate(model, loader, criterion, regression_to_rails, device):
    model.eval()
    total_loss = 0.0
    total_items = 0
    ious = []
    for data, path_gt, ylim_gt in loader:
        data = data.to(device, non_blocking=True)
        target = [path_gt.to(device, non_blocking=True), ylim_gt.to(device, non_blocking=True)]
        output = model(data)
        loss = criterion(output, target)
        bs = data.shape[0]
        total_loss += float(loss.detach().cpu()) * bs
        total_items += bs
